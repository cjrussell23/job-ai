export type IconName = keyof typeof shapes;

export function iconSvg(name: IconName): string {
  return `<svg class="icon" viewBox="0 0 24 24" width="1em" height="1em" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${shapes[name]}</svg>`;
}

const platforms: { match: RegExp; icon: IconName; name: string }[] = [
  { match: /(^|\.)linkedin\.com$/i, icon: "linkedin", name: "LinkedIn" },
  { match: /(^|\.)github\.com$/i, icon: "github", name: "GitHub" },
  { match: /(^|\.)(x|twitter)\.com$/i, icon: "x", name: "X" },
  { match: /(^|\.)(youtube\.com|youtu\.be)$/i, icon: "youtube", name: "YouTube" },
  { match: /(^|\.)instagram\.com$/i, icon: "instagram", name: "Instagram" },
];

/** The platform a link points to, for its icon and default label. */
export function platformOf(url: string): { icon: IconName; name: string } {
  let host = "";
  try {
    host = new URL(url).hostname;
  } catch {
    return { icon: "website", name: "Website" };
  }
  const found = platforms.find((p) => p.match.test(host));
  return found ? { icon: found.icon, name: found.name } : { icon: "website", name: "Website" };
}
